int dms_check_sign_auth_enble(unsigned int dev_id)
{
    int ret;
    struct uda_mia_dev_para mia_para = {0};
    unsigned int phy_id;
    unsigned char auth_flag = 0;
    unsigned int flag_size = sizeof(unsigned char);

    if (!uda_is_phy_dev(dev_id)) {
        ret = uda_udevid_to_mia_devid(dev_id, &mia_para);
        if (ret != 0) {
            dms_err("The udevid to mia devid failed. (udev_id=%u; ret=%d)", dev_id, ret);
            return ret;
        }
        phy_id = mia_para.phy_devid;
    } else {
        phy_id = dev_id;
    }

    ret = hal_kernel_get_user_config(phy_id, AUTH_CONFIG_ENABLE_NAME, &auth_flag, sizeof(unsigned char), &flag_size);
    if (ret != 0) {
        dms_err("Get sign auth enable failed. (devid=%u; ret=%d)\n", phy_id, ret);
        return -EINVAL;
    }

    if (auth_flag != AUTH_CONFIG_ENABLE) {
        dms_warn("Custom sign Auth is disable. (phy_id=%u; conig_value=%u)\n", phy_id, auth_flag);
        return -EOPNOTSUPP;
    }
    return 0;
}

int dms_check_sign_cert(char *buff, unsigned int len)
{
    int ret;
    CMSCBB_VRF_CTX vrf_ctx = NULL;
    CmscbbCtxCreateParams create_params = {0};
 
    create_params.st_size = sizeof(CmscbbCtxCreateParams);
    ret = CmscbbVerifyCreateCtx(&vrf_ctx, &create_params);
    if (ret != 0) {
        dms_err("CmscbbVerifyCreateCtx failed. (ret=0x%x)\n", ret);
        return -EINVAL;
    }

    ret = CmscbbVerifyAddCert(vrf_ctx, (const CVB_BYTE *)buff, len);
    if (ret != 0) {
        dms_err("CmscbbVerifyAddCert failed! (ret=0x%x)\n", ret);
        CmscbbVrfCtxFree(vrf_ctx);
        return -EINVAL;
    }
    CmscbbVrfCtxFree(vrf_ctx);
    return 0;
}

