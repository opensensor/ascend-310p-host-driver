int dms_set_custom_sign_cert(void *feature, char *in, u32 in_len, char *out, u32 out_len, bool sign_check_enable)
{
    int ret = 0;
    unsigned int start = 0;
    struct dms_cert_sync_info *cert_sync_info = NULL;
    struct dms_set_device_info_in_multi_packet *cfg_in = NULL;

    if ((feature == NULL) || (in == NULL) || (in_len != sizeof(struct dms_set_device_info_in_multi_packet)) ||
        (out == NULL) || (out_len != sizeof(struct dms_set_device_info_in_multi_packet))) {
        dms_err("Invalid parameter. (feature=%s; in=%s; in_len=%u; out=%s; out_len=%u)\n",
            (feature == NULL) ? "NULL" : "OK",
            (in == NULL) ? "NULL" : "OK",
            in_len,
            (out == NULL) ? "NULL" : "OK",
            out_len);
        return -EINVAL;
    }

    cfg_in = (struct dms_set_device_info_in_multi_packet *)in;
    if (cfg_in->buff_size > MAX_PACKET_SIZE) {
        dms_err("Invalid parameter buff_size. (buff_size=%u; dev_id=%u)\n", cfg_in->buff_size, cfg_in->dev_id);
        return -EINVAL;
    }

    if (cfg_in->total_size > CUSTOM_SIGN_CONF_FILE_SIZE) {
        dms_err("Invalid parameter total_size. (total_size=%u; dev_id=%u)\n", cfg_in->total_size, cfg_in->dev_id);
        return -EINVAL;
    }

    if (cfg_in->sub_cmd != DSMI_SEC_SUB_CMD_CUST_SIGN_USER_CERT) {
        dms_err("Invalid parameter sub_cmd. (sub_cmd=%u; dev_id=%u)\n", cfg_in->sub_cmd, cfg_in->dev_id);
        return -EINVAL;
    }

    dms_debug("Set custom sign cert. (current_packet=%u; total_size=%u; payload size=%u)\n",
        cfg_in->current_packet,
        cfg_in->total_size,
        cfg_in->buff_size);

    if (!uda_is_udevid_exist(cfg_in->dev_id)) {
        dms_err("device id is not valid. (dev_id=%u)\n", cfg_in->dev_id);
        return -EINVAL;
    }

    if (sign_check_enable) {
        ret = dms_check_sign_auth_enble(cfg_in->dev_id);
        if (ret != 0) {
            return ret;
        }
    }

    cert_sync_info = &g_dms_cert_sync_info[cfg_in->dev_id];
    mutex_lock(&cert_sync_info->cert_sync_lock);

    if (cfg_in->current_packet == 0) {
        if (cert_sync_info->buffer != NULL) {
            dbl_kfree(cert_sync_info->buffer);
            cert_sync_info->buffer = NULL;
        }
        cert_sync_info->buffer = (char *)dbl_kzalloc(CUSTOM_SIGN_CONF_FILE_SIZE, KA_GFP_KERNEL | __KA_GFP_ACCOUNT);
        if (cert_sync_info->buffer == NULL) {
            dms_err("Kzalloc return NULL, failed to alloc mem.\n");
            mutex_unlock(&cert_sync_info->cert_sync_lock);
            return -ENOMEM;
        }
        ret = memset_s(cert_sync_info->buffer, CUSTOM_SIGN_CONF_FILE_SIZE, 0, CUSTOM_SIGN_CONF_FILE_SIZE);
        if (ret != 0) {
            dms_err("Failed to invoke memcpy. (ret=%d)\n", ret);
            dbl_kfree(cert_sync_info->buffer);
            cert_sync_info->buffer = NULL;
            mutex_unlock(&cert_sync_info->cert_sync_lock);
            return -EINVAL;
        }
        cert_sync_info->received_size = 0;
    }

    if (cert_sync_info->buffer == NULL) {
        dms_err("Cert info buffer is empty.(devid=%u)\n", cfg_in->dev_id);
        mutex_unlock(&cert_sync_info->cert_sync_lock);
        return -EINVAL;
    }

    start = cfg_in->current_packet * MAX_PACKET_SIZE;
    if (start > (CUSTOM_SIGN_CONF_FILE_SIZE - cfg_in->buff_size)) {
        dms_err("Packet start len is large than max file size. (devid=%u; start=%u)\n", cfg_in->dev_id, start);
        dbl_kfree(cert_sync_info->buffer);
        cert_sync_info->buffer = NULL;
        mutex_unlock(&cert_sync_info->cert_sync_lock);
        return -EINVAL;
    }

    ret = memcpy_s(cert_sync_info->buffer + start, MAX_PACKET_SIZE, cfg_in->buff, cfg_in->buff_size);
    if (ret != 0) {
        dms_err("Failed to invoke memcpy. (ret=%d)\n", ret);
        dbl_kfree(cert_sync_info->buffer);
        cert_sync_info->buffer = NULL;
        mutex_unlock(&cert_sync_info->cert_sync_lock);
        return -EINVAL;
    }

    cert_sync_info->received_size += cfg_in->buff_size;

    if (cert_sync_info->received_size == cfg_in->total_size) {
        ret = dms_check_sign_cert(cert_sync_info->buffer, cert_sync_info->received_size);
        if (ret != 0) {
            dms_err("Failed to check sign cert. (ret=%d)\n", ret);
            dbl_kfree(cert_sync_info->buffer);
            cert_sync_info->buffer = NULL;
            mutex_unlock(&cert_sync_info->cert_sync_lock);
            return -EINVAL;
        }

        ret = dms_save_sign_cert_to_file(
            cfg_in->dev_id, cfg_in->sub_cmd, cert_sync_info->buffer, cert_sync_info->received_size);
        if (ret != 0) {
            dms_err("Failed to invoke dms_save_sign_cert_to_file. (ret=%d)\n", ret);
            dbl_kfree(cert_sync_info->buffer);
            cert_sync_info->buffer = NULL;
            mutex_unlock(&cert_sync_info->cert_sync_lock);
            return -EINVAL;
        }
        dbl_kfree(cert_sync_info->buffer);
        cert_sync_info->buffer = NULL;
        dms_event("Set custom sign cert success, (dev_id=%u; size=%u)!\n", cfg_in->dev_id, cert_sync_info->received_size);
    }
    mutex_unlock(&cert_sync_info->cert_sync_lock);
    return 0;
}

int dms_get_custom_sign_flag(void *feature, char *in, u32 in_len, char *out, u32 out_len)
{
    int ret;
    unsigned long long file_size;
    long value_tmp = 0;
    char val[CUSTOM_SIGN_CONF_VALLUE_MAX_LEN] = {0};
    char buf[CUSTOM_SIGN_CONF_VALLUE_MAX_LEN] = {0};
    char dst_path[CUSTOM_SIGN_CONF_FILE_PATH_MAX] = {0};
    struct dms_hal_device_info_stru *cfg_in = (struct dms_hal_device_info_stru *)in;
    struct dms_hal_device_info_stru *cfg_out = (struct dms_hal_device_info_stru *)out;

    if ((feature == NULL) || (in == NULL) || (in_len != (DMS_HAL_DEV_INFO_HEAD_LEN + sizeof(unsigned int))) ||
        (out == NULL) || (out_len != (DMS_HAL_DEV_INFO_HEAD_LEN + sizeof(unsigned int)))) {
        dms_err("Invalid parameter. (feature=%s; in=%s; in_len=%u; out=%s; out_len=%u)\n",
                (feature == NULL) ? "NULL" : "OK",
                (in == NULL) ? "NULL" : "OK", in_len, (out == NULL) ? "NULL" : "OK", out_len);
        return -EINVAL;
    }

    ret = snprintf_s(dst_path, CUSTOM_SIGN_CONF_FILE_PATH_MAX, CUSTOM_SIGN_CONF_FILE_PATH_MAX - 1, CUSTOM_SIGN_CONF_FLAG_PATH, cfg_in->dev_id);
    if (ret < 0) {
        dms_err("Failed to invoke snprintf_s, (dev_id=%u; ret=%d).\n", cfg_in->dev_id, ret);
        return -EINVAL;
    }

    ret = dms_custom_get_file_size(dst_path, &file_size);
    if (ret != 0) {
        dms_err("Failed to invoke dms_custom_get_file_size, (dev_id=%u; ret=%d).\n", cfg_in->dev_id, ret);
        return ret;
    }

    if ((file_size == 0) || (file_size >= CUSTOM_SIGN_CONF_VALLUE_MAX_LEN)) {
        dms_err("File size is invalid. (phy_id=%u; file_size=0x%llx)\n", cfg_in->dev_id, file_size);
        return -EINVAL;
    }

    ret = dms_custom_read_file(dst_path, buf, file_size);
    if (ret < 0) {
        dms_err("Failed to invoke dms_custom_read_file, (dev_id=%u; ret=%d).\n", cfg_in->dev_id, ret);
        return -EINVAL;
    }

    ret = search_key_and_get_value(buf, "=", "verify_flag", val, file_size);
    if (ret < 0) {
        dms_err("Failed to invoke search_key_and_get_value, (dev_id=%u; ret=%d).\n", cfg_in->dev_id, ret);
        return -EINVAL;
    }

    if (kstrtol(val, 0, &value_tmp)) {
        dms_err("Failed to invoke kstrtol, (dev_id=%u; ret=%d).\n", cfg_in->dev_id, ret);
        return -EINVAL;
    }

    if (value_tmp >= (long)SIGN_FLAG_MAX) {
        dms_err("Custom sign value is incorrect, (key_word=verify_flag; val=%ld).\n", value_tmp);
        return -EINVAL;
    }

    ret = memcpy_s(cfg_out->payload, sizeof(unsigned int), (unsigned int *)&value_tmp, sizeof(unsigned int));
    if (ret != 0) {
        dms_err("Failed to invoke memcpy_s. (ret=%d; dev_id=%u)\n", ret, cfg_in->dev_id);
    }
    cfg_out->buff_size = sizeof(unsigned int);
    return 0;
}

