int dms_set_custom_sign_flag(void *feature, char *in, u32 in_len, char *out, u32 out_len, bool sign_check_enable)
{
    int ret;
    struct dms_hal_device_info_stru *cfg_in = (struct dms_hal_device_info_stru *)in;
    unsigned int sign_flag = 0;
    long value_len = 0;
    char val[CUSTOM_SIGN_CONF_VALLUE_MAX_LEN] = {0};

    if ((feature == NULL) || (in == NULL) || (in_len < (DMS_HAL_DEV_INFO_HEAD_LEN + cfg_in->buff_size)) || (out == NULL) ||
        (out_len < DMS_HAL_DEV_INFO_HEAD_LEN)) {
        dms_err("Invalid parameter. (feature=%s; in=%s; in_len=%u; out=%s; out_len=%u)\n",
            (feature == NULL) ? "NULL" : "OK",
            (in == NULL) ? "NULL" : "OK",
            in_len,
            (out == NULL) ? "NULL" : "OK",
            out_len);
        return -EINVAL;
    }

    if ((cfg_in->buff_size != sizeof(unsigned int))) {
        dms_err("Invalid parameter. (buff_size=%u; dev_id=%u)\n", cfg_in->buff_size, cfg_in->dev_id);
        return -EINVAL;
    }

    if (!uda_is_udevid_exist(cfg_in->dev_id)) {
        dms_err("device id is not valid. (dev_id=%u)\n", cfg_in->dev_id);
        return -EINVAL;
    }

    if (sign_check_enable) {
        ret = dms_check_sign_auth_enble(cfg_in->dev_id);
        if (ret != 0) {
            return ret;
        }
    }

    ret = memcpy_s(&sign_flag, sizeof(unsigned int), cfg_in->payload, cfg_in->buff_size);
    if (ret != 0) {
        dms_err("Failed to invoke memcpy. (ret=%d)\n", ret);
        return -EINVAL;
    }

    if (sign_flag >= (long)SIGN_FLAG_MAX) {
        dms_err("Custom sign value is incorrect, (sign_flag=%u).\n", sign_flag);
        return -EINVAL;
    }

    value_len = snprintf_s(val, CUSTOM_SIGN_CONF_VALLUE_MAX_LEN, CUSTOM_SIGN_CONF_VALLUE_MAX_LEN - 1, "verify_flag=%u\n", sign_flag);
    if (value_len < 0) {
        dms_err("Failed to invoke snprintf_s, (device_id=%u).\n", cfg_in->dev_id);
        return -EINVAL;
    }

    ret = dms_save_sign_flag_to_file(cfg_in->dev_id, val, value_len);
    if (ret != 0) {
        dms_err("Failed to save sign flag to file, (dev_id=%u).\n", cfg_in->dev_id);
        return -EINVAL;
    }
    dms_event("Set custom sign flag success, (dev_id=%u; sign_flag=%u)!\n", cfg_in->dev_id, sign_flag);
    return 0;
}

